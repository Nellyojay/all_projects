CREATE FUNCTION public.sync_shared_budget_total()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  budget_owner uuid;
  budget_key bigint;
BEGIN
  IF current_setting('app.mythingz_importing', true) = 'on' THEN
    RETURN NULL;
  END IF;
  IF TG_OP <> 'INSERT' THEN
    budget_owner := OLD.user_id;
    budget_key := OLD.budget_id;
    UPDATE public.budgets
      SET total_allocated = COALESCE((
        SELECT SUM(allocated_amount) FROM public.budget_items
        WHERE user_id = budget_owner AND budget_id = budget_key
      ), 0)
      WHERE user_id = budget_owner AND id = budget_key;
  END IF;
  IF TG_OP <> 'DELETE' THEN
    budget_owner := NEW.user_id;
    budget_key := NEW.budget_id;
    UPDATE public.budgets
      SET total_allocated = COALESCE((
        SELECT SUM(allocated_amount) FROM public.budget_items
        WHERE user_id = budget_owner AND budget_id = budget_key
      ), 0), updated_at = NEW.updated_at
      WHERE user_id = budget_owner AND id = budget_key;
  END IF;
  RETURN NULL;
END;
$$;

CREATE TRIGGER shared_budget_total_after_item_change
  AFTER INSERT OR UPDATE OF allocated_amount, budget_id OR DELETE ON public.budget_items
  FOR EACH ROW EXECUTE FUNCTION public.sync_shared_budget_total();

CREATE FUNCTION public.sync_budget_period_to_shared()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  IF current_setting('app.mythingz_importing', true) = 'on' THEN
    RETURN NULL;
  END IF;
  IF TG_OP = 'DELETE' THEN
    DELETE FROM public.budgets WHERE user_id = OLD.user_id AND legacy_period_id = OLD.id;
    RETURN NULL;
  ELSIF TG_OP = 'INSERT' THEN
    INSERT INTO public.budgets
      (user_id, name, type, template_id, start_date, end_date, total_allocated,
       status, legacy_period_id, created_at, updated_at, closed_at)
    SELECT NEW.user_id, templates.name, 'recurring', NEW.template_id, NEW.start_date,
      NEW.end_date, 0, NEW.status, NEW.id, NEW.created_at, NEW.created_at, NEW.closed_at
    FROM public.budget_templates templates
    WHERE templates.user_id = NEW.user_id AND templates.id = NEW.template_id
    ON CONFLICT (user_id, legacy_period_id) DO NOTHING;
    RETURN NULL;
  END IF;

  UPDATE public.budgets
    SET status = NEW.status, start_date = NEW.start_date, end_date = NEW.end_date,
        closed_at = NEW.closed_at, updated_at = clock_timestamp()::text
    WHERE user_id = NEW.user_id AND legacy_period_id = NEW.id;
  RETURN NULL;
END;
$$;

