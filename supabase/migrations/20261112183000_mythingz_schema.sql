    'budget_closures', 'budget_migration_runs', 'record_links', 'reminders',
    'inbox_items', 'activity_logs', 'legacy_unmapped_tables'
  ];
BEGIN
  FOREACH table_name IN ARRAY app_tables LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I USING (user_id = (SELECT auth.uid())) WITH CHECK (user_id = (SELECT auth.uid()))',
      table_name || '_owner_policy',
      table_name
    );
    EXECUTE format('CREATE INDEX %I ON public.%I (user_id)', table_name || '_user_id_idx', table_name);
  END LOOP;
END;
$$;

CREATE FUNCTION public.log_mythingz_activity()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  owner_id uuid;
  record_id_value bigint;
  action_value text;
  module_value text;
  description_value text;
BEGIN
  IF current_setting('app.mythingz_importing', true) = 'on' THEN
    RETURN NULL;
  END IF;

  IF TG_OP = 'DELETE' THEN
    owner_id := OLD.user_id;
    record_id_value := CASE
      WHEN TG_TABLE_NAME = 'list_items' THEN OLD.list_id
      ELSE OLD.id
    END;
    action_value := 'deleted';
  ELSE
    owner_id := NEW.user_id;
    record_id_value := CASE
      WHEN TG_TABLE_NAME = 'list_items' THEN NEW.list_id
      ELSE NEW.id
    END;
    action_value := CASE WHEN TG_OP = 'INSERT' THEN 'created' ELSE 'updated' END;
  END IF;

  IF TG_TABLE_NAME = 'list_items' THEN
    record_id_value := COALESCE(NEW.list_id, OLD.list_id);
    module_value := 'lists';
    description_value := 'List items updated';
  ELSIF TG_TABLE_NAME = 'events' THEN
    module_value := 'events';
    description_value := 'Event ' || action_value;
  ELSIF TG_TABLE_NAME = 'tasks' THEN
    module_value := 'tasks';
    IF TG_OP = 'UPDATE' AND OLD.completed IS DISTINCT FROM NEW.completed THEN
      action_value := CASE WHEN NEW.completed THEN 'completed' ELSE 'reopened' END;
      description_value := CASE WHEN NEW.completed THEN 'Task completed' ELSE 'Task reopened' END;
    ELSE
      description_value := 'Task ' || action_value;
    END IF;
  ELSIF TG_TABLE_NAME = 'notes' THEN
    module_value := 'notes';
    description_value := 'Note ' || action_value;
  ELSIF TG_TABLE_NAME = 'lists' THEN
    module_value := 'lists';
    IF TG_OP = 'UPDATE' AND OLD.finalized IS DISTINCT FROM NEW.finalized THEN
      action_value := 'finalized';
      description_value := CASE WHEN NEW.finalized THEN 'Budget list finalized' ELSE 'Budget list reopened' END;
    ELSE
      description_value := 'List ' || action_value;
    END IF;
  ELSIF TG_TABLE_NAME = 'transactions' THEN
    module_value := 'finances';
    IF TG_OP = 'INSERT' THEN
      description_value := CASE
        WHEN NEW.loan_id IS NOT NULL THEN 'Loan transaction recorded'
        WHEN NEW.category = 'Fees and charges' THEN 'Transfer charge recorded'
        WHEN NEW.kind = 'expense' THEN 'Expense recorded'
        ELSE 'Income recorded'
      END;
    ELSE
      description_value := 'Transaction ' || action_value;
    END IF;
  ELSIF TG_TABLE_NAME = 'transfers' THEN
    module_value := 'finances';
    description_value := 'Transfer ' || action_value;
  ELSIF TG_TABLE_NAME = 'reminders' THEN
    module_value := 'reminders';
    IF TG_OP = 'UPDATE' AND OLD.status IS DISTINCT FROM NEW.status AND NEW.status = 'completed' THEN
      action_value := 'completed';
      description_value := 'Reminder completed';
    ELSE
      description_value := 'Reminder ' || action_value;
    END IF;
  ELSIF TG_TABLE_NAME = 'inbox_items' THEN
    module_value := 'inbox';
    description_value := 'Inbox item ' || action_value;
  ELSE
    module_value := 'links';
    action_value := CASE WHEN TG_OP = 'DELETE' THEN 'unlinked' ELSE 'linked' END;
    description_value := CASE WHEN TG_OP = 'DELETE' THEN 'Record link removed' ELSE 'Records linked' END;
  END IF;

  INSERT INTO public.activity_logs (user_id, action, module, record_id, description, occurred_at)
  VALUES (owner_id, action_value, module_value, record_id_value, description_value, clock_timestamp()::text);
  RETURN NULL;
END;
$$;

