CREATE FUNCTION public.sync_budget_period_item_to_shared()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  budget_key bigint;
  item_key bigint;
  item_position integer;
BEGIN
  IF current_setting('app.mythingz_importing', true) = 'on' THEN
    RETURN NULL;
  END IF;
  IF TG_OP = 'DELETE' THEN
    SELECT budget_item_id INTO item_key FROM public.legacy_budget_item_map
      WHERE user_id = OLD.user_id AND period_item_id = OLD.id;
    DELETE FROM public.budget_items WHERE user_id = OLD.user_id AND id = item_key;
    DELETE FROM public.legacy_budget_item_map
      WHERE user_id = OLD.user_id AND period_item_id = OLD.id;
    RETURN NULL;
  END IF;

  SELECT id INTO budget_key FROM public.budgets
    WHERE user_id = NEW.user_id AND legacy_period_id = NEW.period_id;
  IF budget_key IS NULL THEN
    RAISE EXCEPTION 'No shared budget exists for period %', NEW.period_id;
  END IF;

  IF TG_OP = 'INSERT' THEN
    SELECT COALESCE(MAX(position) + 1, 0) INTO item_position
      FROM public.budget_items WHERE user_id = NEW.user_id AND budget_id = budget_key;
    INSERT INTO public.budget_items
      (user_id, budget_id, template_item_id, name, allocated_amount, original_amount,
       rollover_amount, saved_amount, rollover, alert_thresholds, description, position,
       created_at, updated_at)
    VALUES (NEW.user_id, budget_key, NEW.template_item_id, NEW.name,
      NEW.original_amount + NEW.rollover_amount, NEW.original_amount, NEW.rollover_amount,
      NEW.saved_amount, NEW.rollover, NEW.alert_thresholds, NEW.description, item_position,
      clock_timestamp()::text, clock_timestamp()::text)
    RETURNING id INTO item_key;
    INSERT INTO public.legacy_budget_item_map (user_id, period_item_id, budget_item_id)
      VALUES (NEW.user_id, NEW.id, item_key);
    RETURN NULL;
  END IF;

  UPDATE public.budget_items
    SET name = NEW.name,
        allocated_amount = COALESCE((
          SELECT new_amount FROM public.budget_adjustments
          WHERE user_id = NEW.user_id AND period_item_id = NEW.id
          ORDER BY id DESC LIMIT 1
        ), NEW.original_amount) + NEW.rollover_amount,
        original_amount = NEW.original_amount,
        rollover_amount = NEW.rollover_amount,
        saved_amount = NEW.saved_amount,
        rollover = NEW.rollover,
        alert_thresholds = NEW.alert_thresholds,
        description = NEW.description,
        updated_at = clock_timestamp()::text
    WHERE user_id = NEW.user_id AND id = (
      SELECT budget_item_id FROM public.legacy_budget_item_map
      WHERE user_id = NEW.user_id AND period_item_id = NEW.id
    );
  RETURN NULL;
END;
$$;

