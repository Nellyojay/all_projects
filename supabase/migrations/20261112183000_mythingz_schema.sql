CREATE FUNCTION public.sync_legacy_budget_allocation()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  IF current_setting('app.mythingz_importing', true) = 'on'
     OR NEW.budget_item_id IS NOT NULL OR NEW.period_item_id IS NULL THEN
    RETURN NULL;
  END IF;
  UPDATE public.transaction_allocations allocations
    SET budget_item_id = mapping.budget_item_id,
        budget_id = items.budget_id
    FROM public.legacy_budget_item_map mapping
    JOIN public.budget_items items
      ON items.user_id = mapping.user_id AND items.id = mapping.budget_item_id
    WHERE allocations.user_id = NEW.user_id AND allocations.id = NEW.id
      AND mapping.user_id = NEW.user_id AND mapping.period_item_id = NEW.period_item_id;
  RETURN NULL;
END;
$$;

